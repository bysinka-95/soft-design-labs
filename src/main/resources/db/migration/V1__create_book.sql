CREATE TABLE book (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title  VARCHAR(255) NOT NULL,
    author VARCHAR(255) NOT NULL,
    pages  INTEGER      NOT NULL,
    rating REAL         NOT NULL,
    genre  VARCHAR(32)  NOT NULL
);

